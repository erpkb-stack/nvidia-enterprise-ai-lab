from typing import Literal

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import PlainTextResponse
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from ..catalog import USE_CASES
from ..data.hardware import GPUS, MODELS
from ..database import get_db
from ..models import Architecture, Project
from ..services import architect

router = APIRouter(prefix="/api/v1/architect", tags=["Enterprise Solution Architect Studio"])


class RequirementsIn(BaseModel):
    project_name: str = Field("Enterprise AI POC", min_length=2, max_length=180)
    customer: str = Field("Internal Lab", max_length=180)
    use_case_id: str = "rag-assistant"
    concurrent_users: int = Field(200, ge=1, le=100000)
    input_tokens: int = Field(2048, ge=16, le=131072)
    output_tokens: int = Field(384, ge=1, le=32768)
    max_ttft_ms: float = Field(2000, ge=50, le=60000)
    min_tokens_per_s_per_user: float = Field(20, ge=1, le=500)
    model_size: Literal["small", "medium", "large"] = "small"
    model: str | None = None
    data_sensitivity: Literal["public", "internal", "regulated"] = "internal"
    deployment: Literal["on_prem", "cloud", "hybrid", "air_gapped"] = "on_prem"
    availability: Literal["standard", "high"] = "high"
    document_volume_gb: float = Field(20, ge=0, le=100000)
    gpu_preference: list[str] = Field(default_factory=list)


def _validate(data: RequirementsIn) -> dict:
    if data.use_case_id not in {u["id"] for u in USE_CASES}:
        raise HTTPException(422, "Unknown use case")
    if data.model and data.model not in MODELS:
        raise HTTPException(422, "Unknown model")
    bad = [g for g in data.gpu_preference if g not in GPUS]
    if bad:
        raise HTTPException(422, f"Unknown GPU(s): {', '.join(bad)}")
    return data.model_dump()


@router.post("/design")
def design(data: RequirementsIn):
    return architect.design(_validate(data))


@router.post("/design/save", status_code=201)
def design_and_save(data: RequirementsIn, db: Session = Depends(get_db)):
    result = architect.design(_validate(data))
    p = Project(name=data.project_name, customer=data.customer,
                use_case=result["use_case"]["name"][:120], status="architecture")
    db.add(p)
    db.flush()
    a = Architecture(project_id=p.id, title=result["title"][:180], blueprint=result,
                     rationale=result["summary"])
    db.add(a)
    db.commit()
    return {"project_id": p.id, "architecture_id": a.id, **result}


@router.get("/architectures/{arch_id}/markdown", response_class=PlainTextResponse)
def export_markdown(arch_id: int, db: Session = Depends(get_db)):
    a = db.get(Architecture, arch_id)
    if not a:
        raise HTTPException(404, "Architecture not found")
    md = a.blueprint.get("markdown") if isinstance(a.blueprint, dict) else None
    if not md:
        raise HTTPException(409, "This architecture was not generated by the Architect Studio.")
    return PlainTextResponse(md, headers={
        "Content-Disposition": f'attachment; filename="architecture-{arch_id}.md"'})
